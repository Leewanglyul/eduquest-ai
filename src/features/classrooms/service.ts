const MAX_CODE_ATTEMPTS = 5;

function parse<T>(schema: { safeParse: (v: unknown) => { success: true; data: T } | { success: false; error: { issues: { message: string }[] } } }, input: unknown): T {
  const result = schema.safeParse(input);
  if (!result.success) {
    throw new ClassroomError("VALIDATION_FAILED", result.error.issues[0]?.message ?? "입력값을 확인해 주세요.");
  }
  return result.data;
}

function assertTeacherArea(actor: ClassroomActor) {
  if (!isTeacherArea(actor.role)) {
    throw new ClassroomError("FORBIDDEN", "해당 작업 권한이 없습니다.");
  }
}

/** Loads the classroom with the actor's role; not-visible is reported as NOT_FOUND (no existence leak). */
async function requireClassroom(actor: ClassroomActor, classroomId: string): Promise<ClassroomWithRole> {
  assertTeacherArea(actor);
  const classroom = await getClassroomForActor(actor, classroomId);
  if (!classroom) throw new ClassroomError("NOT_FOUND", "학급을 찾을 수 없습니다.");
  return classroom;
}

function assertActive(classroom: ClassroomRecord) {
  if (isArchived(classroom)) {
    throw new ClassroomError("ARCHIVED", "보관된 학급은 수정할 수 없습니다.");
  }
}

export async function createClassroom(actor: ClassroomActor, rawInput: unknown): Promise<ClassroomRecord> {
  assertTeacherArea(actor);
  const input = parse(createClassroomSchema, rawInput);
  const admin = createSupabaseAdminClient();

  // `code` is generated by the database; retry only on a code collision.
  for (let attempt = 0; attempt < MAX_CODE_ATTEMPTS; attempt += 1) {
    const { data, error } = await admin
      .from("classrooms")
      .insert({ school_id: actor.school_id, owner_id: actor.id, name: input.name })
      .select("*")
      .single();

    if (error?.code === "23505" && error.message.includes("uq_classrooms_code")) continue;
    if (error || !data) {
      throw new ClassroomError("PERSIST_FAILED", "학급을 만들지 못했습니다.");
    }

    await writeAuditLog({
      actorId: actor.id,
      action: "classroom.created",
      resourceType: "classroom",
      resourceId: data.id,
      classroomId: data.id,
      metadata: { schoolId: actor.school_id, name: data.name, code: data.code },
    });
    return toClassroomRecord(data);
  }

  throw new ClassroomError("PERSIST_FAILED", "학급 코드를 생성하지 못했습니다. 다시 시도해 주세요.");
}

/** Owner, co-teacher and admin may edit metadata (name only; the code is read-only). */
export async function updateClassroom(actor: ClassroomActor, rawInput: unknown): Promise<ClassroomRecord> {
  const input = parse(updateClassroomSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canEditClassroom(classroom.role)) throw new ClassroomError("FORBIDDEN", "해당 작업 권한이 없습니다.");
  assertActive(classroom);

  const { data, error } = await createSupabaseAdminClient()
    .from("classrooms")
    .update({ name: input.name })
    .eq("id", classroom.id)
    .select("*")
    .single();
  if (error || !data) throw new ClassroomError("PERSIST_FAILED", "학급을 수정하지 못했습니다.");

  await writeAuditLog({
    actorId: actor.id,
    action: "classroom.updated",
    resourceType: "classroom",
    resourceId: classroom.id,
    classroomId: classroom.id,
    metadata: { previousName: classroom.name, name: data.name },
  });
  return toClassroomRecord(data);
}

async function setArchived(actor: ClassroomActor, rawInput: unknown, archive: boolean): Promise<ClassroomRecord> {
  const input = parse(classroomIdSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canArchiveClassroom(classroom.role)) {
    throw new ClassroomError("FORBIDDEN", "학급 보관은 담임(소유자)만 할 수 있습니다.");
  }
  if (archive && isArchived(classroom)) throw new ClassroomError("ALREADY_ARCHIVED", "이미 보관된 학급입니다.");
  if (!archive && !isArchived(classroom)) throw new ClassroomError("NOT_ARCHIVED", "보관된 학급이 아닙니다.");

  const { data, error } = await createSupabaseAdminClient()
    .from("classrooms")
    .update({ archived_at: archive ? new Date().toISOString() : null })
    .eq("id", classroom.id)
    .select("*")
    .single();
  if (error || !data) throw new ClassroomError("PERSIST_FAILED", "학급 상태를 변경하지 못했습니다.");

  await writeAuditLog({
    actorId: actor.id,
    action: archive ? "classroom.archived" : "classroom.unarchived",
    resourceType: "classroom",
    resourceId: classroom.id,
    classroomId: classroom.id,
    metadata: { name: classroom.name },
  });
  return toClassroomRecord(data);
}

export const archiveClassroom = (actor: ClassroomActor, input: unknown) => setArchived(actor, input, true);
export const unarchiveClassroom = (actor: ClassroomActor, input: unknown) => setArchived(actor, input, false);

export async function addCoTeacher(actor: ClassroomActor, rawInput: unknown): Promise<void> {
  const input = parse(coTeacherSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canManageCoTeachers(classroom.role)) {
    throw new ClassroomError("FORBIDDEN", "공동 담임 관리는 담임(소유자)만 할 수 있습니다.");
  }
  assertActive(classroom);
  if (input.teacherId === classroom.ownerId) {
    throw new ClassroomError("CO_TEACHER_INVALID", "담임(소유자)은 공동 담임으로 추가할 수 없습니다.");
  }

  const admin = createSupabaseAdminClient();
  const { data: target } = await admin
    .from("profiles")
    .select("id, role, status, school_id")
    .eq("id", input.teacherId)
    .maybeSingle();
  if (
    !target ||
    target.school_id !== classroom.schoolId ||
    target.status !== "active" ||
    (target.role !== "teacher" && target.role !== "admin")
  ) {
    throw new ClassroomError("CO_TEACHER_INVALID", "공동 담임으로 추가할 수 없는 교사입니다.");
  }

  const { error } = await admin
    .from("classroom_teachers")
    .insert({ classroom_id: classroom.id, teacher_id: input.teacherId, added_by: actor.id });
  if (error?.code === "23505") throw new ClassroomError("CO_TEACHER_EXISTS", "이미 공동 담임으로 등록된 교사입니다.");
  if (error) throw new ClassroomError("PERSIST_FAILED", "공동 담임을 추가하지 못했습니다.");

  await writeAuditLog({
    actorId: actor.id,
    action: "classroom.co_teacher_added",
    resourceType: "classroom_teacher",
    resourceId: classroom.id,
    classroomId: classroom.id,
    metadata: { teacherId: input.teacherId },
  });
}

export async function removeCoTeacher(actor: ClassroomActor, rawInput: unknown): Promise<void> {
  const input = parse(coTeacherSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canManageCoTeachers(classroom.role)) {
    throw new ClassroomError("FORBIDDEN", "공동 담임 관리는 담임(소유자)만 할 수 있습니다.");
  }

  const { data, error } = await createSupabaseAdminClient()
    .from("classroom_teachers")
    .delete()
    .eq("classroom_id", classroom.id)
    .eq("teacher_id", input.teacherId)
    .select("teacher_id");
  if (error) throw new ClassroomError("PERSIST_FAILED", "공동 담임을 해제하지 못했습니다.");
  if (!data || data.length === 0) {
    throw new ClassroomError("CO_TEACHER_NOT_FOUND", "공동 담임으로 등록되어 있지 않습니다.");
  }

  await writeAuditLog({
    actorId: actor.id,
    action: "classroom.co_teacher_removed",
    resourceType: "classroom_teacher",
    resourceId: classroom.id,
    classroomId: classroom.id,
    metadata: { teacherId: input.teacherId },
  });
}

/** Adds a student to the roster, reactivating a previously removed enrollment. */
export async function addStudentToClassroom(actor: ClassroomActor, rawInput: unknown): Promise<string> {
  const input = parse(enrollmentSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canManageRoster(classroom.role)) throw new ClassroomError("FORBIDDEN", "해당 작업 권한이 없습니다.");
  assertActive(classroom);

  const admin = createSupabaseAdminClient();
  const { data: student } = await admin
    .from("students")
    .select("id")
    .eq("id", input.studentId)
    .eq("school_id", classroom.schoolId)
    .maybeSingle();
  if (!student) throw new ClassroomError("STUDENT_NOT_FOUND", "학생을 찾을 수 없습니다.");

  const { data: existing } = await admin
    .from("classroom_enrollments")
    .select("id, status")
    .eq("classroom_id", classroom.id)
    .eq("student_id", input.studentId)
    .maybeSingle();

  if (existing?.status === "active") {
    throw new ClassroomError("ENROLLMENT_EXISTS", "이미 학급에 등록된 학생입니다.");
  }

  if (existing) {
    const { error } = await admin
      .from("classroom_enrollments")
      .update({ status: "active", removed_at: null, enrolled_at: new Date().toISOString() })
      .eq("id", existing.id)
      .eq("status", "removed");
    if (error) throw new ClassroomError("PERSIST_FAILED", "학생을 다시 등록하지 못했습니다.");

    await writeAuditLog({
      actorId: actor.id,
      action: "enrollment.reactivated",
      resourceType: "enrollment",
      resourceId: existing.id,
      classroomId: classroom.id,
      metadata: { studentId: input.studentId },
    });
    return existing.id;
  }

  const { data: created, error } = await admin
    .from("classroom_enrollments")
    .insert({ classroom_id: classroom.id, student_id: input.studentId })
    .select("id")
    .single();
  if (error?.code === "23505") throw new ClassroomError("ENROLLMENT_EXISTS", "이미 학급에 등록된 학생입니다.");
  if (error || !created) throw new ClassroomError("PERSIST_FAILED", "학생을 등록하지 못했습니다.");

  await writeAuditLog({
    actorId: actor.id,
    action: "enrollment.added",
    resourceType: "enrollment",
    resourceId: created.id,
    classroomId: classroom.id,
    metadata: { studentId: input.studentId },
  });
  return created.id;
}

export async function removeStudentFromClassroom(actor: ClassroomActor, rawInput: unknown): Promise<void> {
  const input = parse(enrollmentSchema, rawInput);
  const classroom = await requireClassroom(actor, input.classroomId);
  if (!canManageRoster(classroom.role)) throw new ClassroomError("FORBIDDEN", "해당 작업 권한이 없습니다.");
  assertActive(classroom);

  const { data, error } = await createSupabaseAdminClient()
    .from("classroom_enrollments")
    .update({ status: "removed", removed_at: new Date().toISOString() })
    .eq("classroom_id", classroom.id)
    .eq("student_id", input.studentId)
    .eq("status", "active")
    .select("id");
  if (error) throw new ClassroomError("PERSIST_FAILED", "학생을 제외하지 못했습니다.");
  if (!data || data.length === 0) {
    throw new ClassroomError("ENROLLMENT_NOT_FOUND", "학급에 등록된 학생이 아닙니다.");
  }

  await writeAuditLog({
    actorId: actor.id,
    action: "enrollment.removed",
    resourceType: "enrollment",
    resourceId: data[0].id,
    classroomId: classroom.id,
    metadata: { studentId: input.studentId },
  });
}

const TRANSFER_MESSAGES: Record<string, [ClassroomError["code"], string]> = {
  TRANSFER_SAME_CLASSROOM: ["VALIDATION_FAILED", "같은 학급으로는 이동할 수 없습니다."],
  TRANSFER_FORBIDDEN: ["FORBIDDEN", "두 학급 모두의 담임 또는 공동 담임이어야 이동할 수 있습니다."],
  TRANSFER_CLASSROOM_NOT_FOUND: ["NOT_FOUND", "학급을 찾을 수 없습니다."],
  TRANSFER_CLASSROOM_ARCHIVED: ["ARCHIVED", "보관된 학급으로/에서는 이동할 수 없습니다."],
  TRANSFER_CROSS_SCHOOL: ["FORBIDDEN", "다른 학교의 학급으로는 이동할 수 없습니다."],
  TRANSFER_STUDENT_NOT_FOUND: ["STUDENT_NOT_FOUND", "학생을 찾을 수 없습니다."],
  TRANSFER_NOT_ENROLLED: ["ENROLLMENT_NOT_FOUND", "원래 학급에 등록된 학생이 아닙니다."],
  TRANSFER_ALREADY_ENROLLED: ["ENROLLMENT_EXISTS", "이미 대상 학급에 등록된 학생입니다."],
};

/** Thin wrapper over the atomic fn_transfer_enrollment RPC (which also writes the audit row). */
export async function transferStudent(actor: ClassroomActor, rawInput: unknown): Promise<string> {
  const input = parse(transferSchema, rawInput);
  assertTeacherArea(actor);

  // Pre-check visibility so non-members get NOT_FOUND rather than RPC detail.
  await requireClassroom(actor, input.sourceClassroomId);
  await requireClassroom(actor, input.targetClassroomId);

  const { data, error } = await createSupabaseAdminClient().rpc("fn_transfer_enrollment", {
    source_classroom_id: input.sourceClassroomId,
    target_classroom_id: input.targetClassroomId,
    student_id: input.studentId,
    actor_id: actor.id,
  });

  if (error) {
    const key = Object.keys(TRANSFER_MESSAGES).find((k) => error.message.includes(k));
    if (key) {
      const [code, message] = TRANSFER_MESSAGES[key];
      throw new ClassroomError(code, message);
    }
    throw new ClassroomError("TRANSFER_FAILED", "학생을 이동하지 못했습니다.");
  }
  return data as string;
}
